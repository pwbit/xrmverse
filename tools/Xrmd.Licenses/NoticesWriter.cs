using System.Text;
using System.Text.RegularExpressions;

namespace Xrmd.Licenses;

/// <summary>
/// Writes <c>THIRD_PARTY_NOTICES.md</c>: one section per shipped package, then each standard license text once, then the
/// own license terms of packages whose license is not a standard one. Deterministic: sorted, no dates, LF line endings.
/// </summary>
public static partial class NoticesWriter
{
    private static readonly IReadOnlyDictionary<string, string> EcosystemTitles = new Dictionary<string, string>
    {
        ["generic"] = "Software built into the server image",
        ["npm"] = "npm packages (web admin)",
        ["nuget"] = "NuGet packages (server and `xrmd` CLI)",
    };

    public static string Write(IReadOnlyList<Package> packages, LicensePolicy policy)
    {
        var shipped = Inventory.Sort(packages.Where(p => p.Shipped));
        var sb = new StringBuilder();
        sb.Append("# Third-party notices\n\n");
        sb.Append("This file lists the third-party software included in the xrmverse server image, the `xrmd` CLI and the web admin, ");
        sb.Append("with the license under which each component is distributed and its copyright notice. ");
        sb.Append("The license texts follow the list.\n\n");
        sb.Append("This file is generated by `eng/licenses.sh notices --out THIRD_PARTY_NOTICES.md`; do not edit it by hand.\n");

        var standardIds = new SortedSet<string>(StringComparer.Ordinal);
        var nonStandard = new List<Package>();
        var attributionFiles = new Dictionary<string, (int Number, List<Package> Users)>(StringComparer.Ordinal);
        foreach (var group in shipped.GroupBy(p => p.Ecosystem))
        {
            sb.Append("\n## ").Append(EcosystemTitles.TryGetValue(group.Key, out var title) ? title : group.Key).Append('\n');
            foreach (var p in group)
            {
                sb.Append("\n### ").Append(p.Id).Append(' ').Append(p.Version).Append("\n\n");
                if (p.Description is not null)
                {
                    sb.Append("- Included: ").Append(OneLine(p.Description)).Append('\n');
                }

                sb.Append("- License: ").Append(p.License).Append('\n');
                AppendCopyright(sb, p.Copyright);
                sb.Append("- Project URL: ").Append(OneLine(p.ProjectUrl) ?? "not stated by the package").Append('\n');

                var leaves = SpdxExpression.TryParse(p.License)?.Licenses().ToArray();
                var texts = leaves?.Where(l => l.Exception is null).Select(l => policy.StandardText(l.Id) is null ? null : policy.CanonicalId(l.Id)).ToArray();
                var isNonStandard = texts is null || texts.Length != leaves!.Length || texts.Any(t => t is null);
                if (isNonStandard)
                {
                    nonStandard.Add(p);
                    sb.Append("- License terms: see \"").Append(p.Id).Append(' ').Append(p.Version)
                        .Append(" license terms\" under \"Packages under their own license terms\"\n");
                }
                else if (p.EmbedLicenseText && p.LicenseText is not null)
                {
                    var key = p.LicenseText.TrimEnd();
                    if (!attributionFiles.TryGetValue(key, out var file))
                    {
                        attributionFiles[key] = file = (attributionFiles.Count + 1, new List<Package>());
                    }

                    file.Users.Add(p);
                    sb.Append("- License file: states no copyright line; reproduced below as \"License file ")
                        .Append(file.Number).Append("\"\n");
                }

                if (p.NoticeText is not null)
                {
                    sb.Append("\nThe NOTICE file of the package:\n\n");
                    AppendFenced(sb, p.NoticeText);
                }

                foreach (var id in texts?.Where(t => t is not null) ?? Enumerable.Empty<string?>())
                {
                    standardIds.Add(id!);
                }
            }
        }

        if (standardIds.Count > 0)
        {
            sb.Append("\n## License texts\n");
            foreach (var id in standardIds)
            {
                sb.Append("\n### ").Append(id).Append("\n\n");
                AppendFenced(sb, policy.StandardText(id)!);
            }
        }

        if (attributionFiles.Count > 0)
        {
            sb.Append("\n## License files reproduced for attribution\n\n");
            sb.Append("These packages state no copyright line, so their license files are reproduced verbatim.\n");
            foreach (var (text, (number, users)) in attributionFiles.OrderBy(f => f.Value.Number))
            {
                sb.Append("\n### License file ").Append(number).Append("\n\n");
                sb.Append("Used by: ").Append(string.Join(", ", users.Select(u => $"{u.Id} {u.Version}"))).Append(".\n\n");
                AppendFenced(sb, text);
            }
        }

        if (nonStandard.Count > 0)
        {
            sb.Append("\n## Packages under their own license terms\n");
            foreach (var p in nonStandard)
            {
                sb.Append("\n### ").Append(p.Id).Append(' ').Append(p.Version).Append(" license terms\n\n");
                if (p.LicenseText is not null)
                {
                    sb.Append("The license file included in the package:\n\n");
                    AppendFenced(sb, p.LicenseText);
                }
                else if (p.LicenseUrl is not null)
                {
                    sb.Append("The package states its license at ").Append(p.LicenseUrl).Append(" and includes no license file.\n");
                }
                else
                {
                    sb.Append("The package states no license file and no license URL.\n");
                }
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// Compares a committed notices file with the freshly generated one. Returns nothing when they are equal; otherwise
    /// one message per package added, removed or changed in version, or one general message.
    /// </summary>
    public static IReadOnlyList<string> Compare(string committed, string generated, string fileName)
    {
        committed = committed.Replace("\r\n", "\n");
        if (committed == generated)
        {
            return Array.Empty<string>();
        }

        var regenerate = "regenerate it with eng/licenses.sh notices --out THIRD_PARTY_NOTICES.md";
        var before = ListedPackages(committed);
        var after = ListedPackages(generated);
        var messages = new List<string>();
        foreach (var id in before.Keys.Union(after.Keys).OrderBy(k => k, StringComparer.Ordinal))
        {
            var old = before.TryGetValue(id, out var o) ? o : new SortedSet<string>(StringComparer.Ordinal);
            var now = after.TryGetValue(id, out var n) ? n : new SortedSet<string>(StringComparer.Ordinal);
            if (old.SetEquals(now))
            {
                continue;
            }

            if (old.Count == 0)
            {
                messages.Add($"{fileName} is out of date: {id} {string.Join(", ", now)} is shipped but not listed; {regenerate}");
            }
            else if (now.Count == 0)
            {
                messages.Add($"{fileName} is out of date: {id} {string.Join(", ", old)} is listed but no longer shipped; {regenerate}");
            }
            else
            {
                messages.Add($"{fileName} is out of date: {id} is listed as {string.Join(", ", old)} but the build ships {string.Join(", ", now)}; {regenerate}");
            }
        }

        if (messages.Count == 0)
        {
            messages.Add($"{fileName} is out of date (license, copyright or license text changed); {regenerate}");
        }

        return messages;
    }

    private static Dictionary<string, SortedSet<string>> ListedPackages(string notices)
    {
        var result = new Dictionary<string, SortedSet<string>>(StringComparer.Ordinal);
        foreach (Match m in PackageHeading().Matches(notices))
        {
            var id = m.Groups["id"].Value;
            if (!result.TryGetValue(id, out var versions))
            {
                result[id] = versions = new SortedSet<string>(StringComparer.Ordinal);
            }

            versions.Add(m.Groups["version"].Value);
        }

        return result;
    }

    [GeneratedRegex(@"^### (?<id>\S+) (?<version>\S+)$", RegexOptions.Multiline)]
    private static partial Regex PackageHeading();

    private static void AppendCopyright(StringBuilder sb, string? copyright)
    {
        var lines = (copyright ?? string.Empty).Split('\n').Select(l => OneLine(l)).OfType<string>().ToArray();
        if (lines.Length == 0)
        {
            sb.Append("- Copyright: not stated by the package\n");
        }
        else if (lines.Length == 1)
        {
            sb.Append("- Copyright: ").Append(lines[0]).Append('\n');
        }
        else
        {
            sb.Append("- Copyright:\n");
            foreach (var line in lines)
            {
                sb.Append("  - ").Append(line).Append('\n');
            }
        }
    }

    private static string? OneLine(string? text) =>
        string.IsNullOrWhiteSpace(text) ? null : Regex.Replace(text.Trim(), @"\s*\n\s*", " ");

    private static void AppendFenced(StringBuilder sb, string text)
    {
        var longestRun = Regex.Matches(text, "`+").Select(m => m.Length).DefaultIfEmpty(0).Max();
        var fence = new string('`', Math.Max(3, longestRun + 1));
        sb.Append(fence).Append("text\n").Append(text.TrimEnd('\n', ' ', '\t')).Append('\n').Append(fence).Append('\n');
    }
}
