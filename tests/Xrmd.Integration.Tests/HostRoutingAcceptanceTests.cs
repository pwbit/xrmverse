/// <summary>
/// Spec 2.19 acceptance: host-name routing through a real Caddy. The installation is generated by the real
/// <c>xrmd server init --domain xrm.test --tls internal</c>; each organization runs as an <c>Xrmd.Host</c> process with the
/// resolved environment of its compose service (the plan 9 model, ruling M9, see <see cref="MultiOrgAcceptanceTests"/>), behind
/// a Caddy container (<see cref="ComposeRenderer.CaddyImage"/>) on host port 443 that runs the <c>Caddyfile</c> rendered by
/// <see cref="CaddyfileRenderer"/>. What the emulation changes, and why:
/// <list type="bullet">
/// <item>The Caddyfile's upstream is <c>host.docker.internal:&lt;ORG_&lt;ORG&gt;_PORT&gt;</c> (the container has
/// <c>--add-host host.docker.internal:host-gateway</c>) instead of <c>xrmd-&lt;org&gt;:5000</c> on the compose network: the
/// hosts are processes, not containers. Everything else of the Caddyfile is the rendered text.</item>
/// <item>Each host listens on the Docker bridge gateway (the address <c>host.docker.internal</c> resolves to in the container),
/// so only the bridge reaches it, as only the <c>edge</c> network reaches an organization's container.</item>
/// <item><c>Proxy__TrustedProxies</c> is the address the host processes see Caddy's connections come from: the Caddy
/// container's address on the bridge (traffic from a container to the bridge gateway is not translated), in place of the
/// proxy's fixed <c>edge</c> address. <c>Proxy__AllowedHosts</c> is the generated one.</item>
/// </list>
/// The test's <see cref="HttpClient"/>s resolve <c>*.xrm.test</c> to 127.0.0.1 with a <c>ConnectCallback</c> and trust Caddy's
/// internal root, exported from the container, with <see cref="ScopedTrust"/> for their own host only. What this test cannot
/// check (ServiceClient through real name resolution; no xrmd port published by a real <c>server up</c>) is checked
/// by hand. Needs Docker and a free host port 443.
/// </summary>
[Trait("Category", "Acceptance")]
[Collection("host-port-443")]
public sealed class HostRoutingAcceptanceTests(ITestOutputHelper output) : IAsyncLifetime
{
    private const string Domain = "xrm.test";
    private const string CaddyfileInContainer = "/etc/caddy/Caddyfile";
    private const string CaddyRootInContainer = "/data/caddy/pki/authorities/local/root.crt";

    private readonly string _root = Path.Combine(Path.GetTempPath(), "xrmd-hostrouting-acceptance", Guid.NewGuid().ToString("N"));
    private readonly List<HostProcess> _hosts = [];
    private readonly Dictionary<string, HttpClient> _clients = new(StringComparer.Ordinal);
    private MsSqlContainer? _sql;
    private IContainer? _caddy;
    private X509Certificate2? _caddyRoot;
    private string _hostFolder = "";
    private string _sdk = "";
    private string _gateway = "";
    private string _caddyAddress = "";

    private string InstallDir => Path.Combine(_root, "install");
    private string ConfigDir => Path.Combine(_root, "config");
    private string FilesRoot => Path.Combine(_root, "files");

    /// <summary>The Caddyfile bind-mounted into the proxy container (rewritten in place, as the CLI does: the mount keeps its inode).</summary>
    private string ProxyCaddyfile => Path.Combine(_root, "proxy", "Caddyfile");

    public async Task InitializeAsync()
    {
        _hostFolder = await PublishedApps.HostAsync();
        _sdk = await PublishedApps.InstalledSdkAsync();
    }

    public async Task DisposeAsync()
    {
        foreach (var host in _hosts) host.Dispose();
        foreach (var client in _clients.Values) client.Dispose();
        _caddyRoot?.Dispose();
        if (_caddy is not null) await _caddy.DisposeAsync();
        if (_sql is not null) await _sql.DisposeAsync();
        try { Directory.Delete(_root, recursive: true); } catch (DirectoryNotFoundException) { }
        PublishedApps.DeleteFolder(_sdk);
    }

    [Fact]
    public async Task Organizations_are_routed_by_host_name_through_caddy_and_a_new_one_is_added_by_a_reload()
    {
        // The installation: two organizations with public hosts <org>.xrm.test behind the generated Caddy proxy, TLS internal.
        var cli = new MultiOrgCli(ConfigDir);
        (await cli.RunAsync("server", "init", "--accept-sql-server-eula", "--dir", InstallDir, "--org", "acme", "--org", "zenith", "--domain", Domain, "--tls", "internal"))
            .Should().Be(0, cli.Err);
        var env = MultiOrgHarness.ReadEnv(InstallDir);
        cli.SigningKey = env["AUTH_DEV_SIGNING_KEY"];
        var installation = Installation.Load(InstallDir);
        installation.Proxy.Should().Be(ProxyMode.Caddy);
        installation.Orgs.Select(o => o.Host).Should().Equal("acme.xrm.test", "zenith.xrm.test");
        File.ReadAllText(installation.CaddyfilePath).Should().Be(CaddyfileRenderer.Render(installation), "the CLI wrote the rendered Caddyfile");

        _sql = new MsSqlBuilder("mcr.microsoft.com/mssql/server:2022-latest").WithPassword(env["SA_PASSWORD"]).Build();
        await _sql.StartAsync();

        // Caddy first: the hosts trust its address. The upstreams answer 502 until the hosts are up.
        await StartCaddyAsync(installation);
        var services = await MultiOrgHarness.ResolvedServicesAsync(InstallDir);
        services["xrmd-acme"].TryGetProperty("ports", out _).Should().BeFalse("behind Caddy an organization publishes no host port (H6)");
        var acme = StartHost(installation, "acme", services["xrmd-acme"]);
        var zenith = StartHost(installation, "zenith", services["xrmd-zenith"]);

        // 1. /healthz of each organization through Caddy on 443, by host name.
        await Task.WhenAll(WaitHealthyAsync(acme, "acme.xrm.test"), WaitHealthyAsync(zenith, "zenith.xrm.test"));

        // 2. A paged Web API query on acme: the next link is built from the forwarded scheme and host.
        var config = new ProfileStore(ConfigDir).Load();
        config.Profiles["acme"].Url.Should().Be("https://acme.xrm.test/");
        var acmeToken = await new DevTokenProvider(config.Profiles["acme"], cli.Env()).GetTokenAsync(CancellationToken.None);
        Audience(acmeToken).Should().Be("https://acme.xrm.test/");
        var acmeHttp = Client("acme.xrm.test");
        foreach (var name in new[] { "Routed 1", "Routed 2", "Routed 3" })
        {
            using var create = Request(HttpMethod.Post, "https://acme.xrm.test/api/data/v9.2/accounts", acmeToken);
            create.Content = new StringContent(new JsonObject { ["name"] = name }.ToJsonString(), Encoding.UTF8, "application/json");
            var created = await acmeHttp.SendAsync(create);
            created.StatusCode.Should().Be(HttpStatusCode.NoContent, await created.Content.ReadAsStringAsync());
            created.Headers.TryGetValues("OData-EntityId", out var entityId).Should().BeTrue();
            entityId!.Single().Should().StartWith("https://acme.xrm.test/api/data/v9.2/accounts(");
        }

        var names = new List<string>();
        string? url = "https://acme.xrm.test/api/data/v9.2/accounts?$select=name&$orderby=name";
        var pages = 0;
        while (url is not null)
        {
            using var get = Request(HttpMethod.Get, url, acmeToken);
            get.Headers.Add("Prefer", "odata.maxpagesize=2");
            var response = await acmeHttp.SendAsync(get);
            var body = await response.Content.ReadAsStringAsync();
            response.StatusCode.Should().Be(HttpStatusCode.OK, body);
            var json = JsonNode.Parse(body)!.AsObject();
            names.AddRange(json["value"]!.AsArray().Select(v => v!["name"]!.GetValue<string>()));
            url = json["@odata.nextLink"]?.GetValue<string>();
            if (pages++ == 0)
                url.Should().NotBeNull().And.StartWith("https://acme.xrm.test/", "the next link is the public URL Caddy was asked for");
        }
        pages.Should().Be(2);
        names.Should().Equal("Routed 1", "Routed 2", "Routed 3");

        // 3. A token for acme (audience https://acme.xrm.test/) is refused by zenith; accepted by acme.
        (await WhoAmIStatusAsync("acme.xrm.test", acmeToken)).Should().Be(HttpStatusCode.OK);
        (await WhoAmIStatusAsync("zenith.xrm.test", acmeToken)).Should().Be(HttpStatusCode.Unauthorized);

        // 4. `server org add orbit`, a new host process, the re-rendered Caddyfile and `caddy reload`: orbit answers,
        //    acme and zenith keep serving through Caddy and their processes are not restarted.
        var acmeStart = acme.StartTime;
        var zenithStart = zenith.StartTime;
        using var watch = new HealthWatch([
            ("acme", acmeHttp, "https://acme.xrm.test/healthz"),
            ("zenith", Client("zenith.xrm.test"), "https://zenith.xrm.test/healthz"),
        ]);

        var docker = new RecordingProcessRunner();
        cli.Process = docker;
        CopyDirectory(_sdk, Path.Combine(InstallDir, "sdk")); // `org add` refuses to start containers without <dir>/sdk/sdk.json
        (await cli.RunAsync("server", "org", "add", "orbit", "--dir", InstallDir)).Should().Be(0, cli.Err);
        docker.Calls.Select(c => string.Join(' ', c.Arguments.TakeLast(3))).Should().Contain("up -d xrmd-orbit");
        installation = Installation.Load(InstallDir);
        installation.Orgs.Single(o => o.Name == "orbit").Host.Should().Be("orbit.xrm.test");
        File.ReadAllText(installation.CaddyfilePath).Should().Be(CaddyfileRenderer.Render(installation)).And.Contain("orbit.xrm.test {");

        var orbit = StartHost(installation, "orbit", (await MultiOrgHarness.ResolvedServicesAsync(InstallDir))["xrmd-orbit"]);
        await WaitListeningAsync(orbit);
        await WriteProxyCaddyfileAsync(installation);
        // The command `server org add` runs in the proxy container (`docker compose exec -T proxy caddy reload ...`).
        var reload = await _caddy!.ExecAsync(["caddy", "reload", "--config", CaddyfileInContainer]);
        reload.ExitCode.Should().Be(0, reload.Stdout + reload.Stderr);
        await WaitHealthyAsync(orbit, "orbit.xrm.test");

        var failures = await watch.StopAsync();
        failures.Should().BeEmpty("acme and zenith answer /healthz through Caddy throughout the reload");
        watch.Probes.Should().BeGreaterThan(0);
        foreach (var (host, start) in new[] { (acme, acmeStart), (zenith, zenithStart) })
        {
            host.HasExited.Should().BeFalse($"{host.Name} keeps running");
            System.Diagnostics.Process.GetProcessById(host.Id).StartTime.Should().Be(start, $"{host.Name} was not restarted");
        }
        (await WhoAmIStatusAsync("acme.xrm.test", acmeToken)).Should().Be(HttpStatusCode.OK, "acme keeps serving");
    }

    /// <summary>
    /// Starts <see cref="ComposeRenderer.CaddyImage"/> on host port 443 with the rendered Caddyfile, then records the address
    /// <c>host.docker.internal</c> resolves to in it (where the hosts listen), its own bridge address (what the hosts trust),
    /// and exports its internal root (what the clients trust).
    /// </summary>
    private async Task StartCaddyAsync(Installation installation)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(ProxyCaddyfile)!);
        await WriteProxyCaddyfileAsync(installation);
        _caddy = new ContainerBuilder(ComposeRenderer.CaddyImage)
            .WithPortBinding(443, 443)
            .WithExtraHost("host.docker.internal", "host-gateway")
            .WithBindMount(ProxyCaddyfile, CaddyfileInContainer, AccessMode.ReadOnly)
            .WithWaitStrategy(Wait.ForUnixContainer().UntilMessageIsLogged("serving initial configuration"))
            .Build();
        await _caddy.StartAsync();

        var resolved = await _caddy.ExecAsync(["getent", "hosts", "host.docker.internal"]);
        resolved.ExitCode.Should().Be(0, resolved.Stderr);
        _gateway = resolved.Stdout.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries)[0];
        IPAddress.Parse(_gateway).AddressFamily.Should().Be(AddressFamily.InterNetwork);
        _caddyAddress = _caddy.IpAddress;
        IPAddress.Parse(_caddyAddress).AddressFamily.Should().Be(AddressFamily.InterNetwork);
        output.WriteLine($"Caddy {ComposeRenderer.CaddyImage} at {_caddyAddress}; hosts listen on the bridge gateway {_gateway}");

        // The local CA is created while Caddy provisions the first internal certificates.
        var deadline = DateTime.UtcNow + TimeSpan.FromSeconds(30);
        byte[]? pem = null;
        while (pem is null)
        {
            try
            {
                pem = await _caddy.ReadFileAsync(CaddyRootInContainer);
            }
            catch (Exception) when (DateTime.UtcNow < deadline)
            {
                await Task.Delay(500);
            }
        }
        var rootPath = Path.Combine(_root, "caddy-root.crt");
        await File.WriteAllBytesAsync(rootPath, pem);
        _caddyRoot = ScopedTrust.LoadRoot(rootPath);
    }

    /// <summary>The rendered Caddyfile with the hosts as upstreams (see the class remarks), written in place.</summary>
    private Task WriteProxyCaddyfileAsync(Installation installation) =>
        File.WriteAllTextAsync(ProxyCaddyfile, CaddyfileRenderer.Render(installation,
            org => $"host.docker.internal:{org.Port.ToString(System.Globalization.CultureInfo.InvariantCulture)}"));

    /// <summary>Starts the organization's host on <c>&lt;gateway&gt;:ORG_&lt;ORG&gt;_PORT</c>, trusting Caddy's bridge address.</summary>
    private HostProcess StartHost(Installation installation, string org, JsonElement service)
    {
        var environment = service.GetProperty("environment");
        environment.GetProperty("Proxy__AllowedHosts").GetString().Should().Be($"{org}.{Domain}");
        environment.GetProperty("Auth__Audience").GetString().Should().Be($"https://{org}.{Domain}/");
        var port = installation.Orgs.Single(o => o.Name == org).Port;
        var host = MultiOrgHarness.StartHost(org, port, service, _hostFolder,
            new SqlConnectionStringBuilder(_sql!.GetConnectionString()).DataSource, $"http://{_gateway}:{port}", FilesRoot, _sdk, output,
            new Dictionary<string, string> { ["Proxy__TrustedProxies"] = _caddyAddress });
        _hosts.Add(host);
        return host;
    }

    /// <summary>A client for one public host: <c>*.xrm.test</c> connects to 127.0.0.1 (Caddy's 443), Caddy's root trusted for this host only.</summary>
    private HttpClient Client(string host)
    {
        if (_clients.TryGetValue(host, out var existing)) return existing;
        var handler = ScopedTrust.CreateHandler(host, _caddyRoot!);
        handler.UseProxy = false; // straight to Caddy, whatever HTTPS_PROXY of the machine says
        handler.ConnectCallback = async (context, cancellationToken) =>
        {
            if (!context.DnsEndPoint.Host.EndsWith("." + Domain, StringComparison.OrdinalIgnoreCase))
                throw new HttpRequestException($"This test only resolves *.{Domain}: {context.DnsEndPoint.Host}");
            var socket = new Socket(SocketType.Stream, ProtocolType.Tcp) { NoDelay = true };
            try
            {
                await socket.ConnectAsync(new IPEndPoint(IPAddress.Loopback, context.DnsEndPoint.Port), cancellationToken);
                return new NetworkStream(socket, ownsSocket: true);
            }
            catch
            {
                socket.Dispose();
                throw;
            }
        };
        var client = new HttpClient(handler) { Timeout = TimeSpan.FromSeconds(30) };
        _clients[host] = client;
        return client;
    }

    private static HttpRequestMessage Request(HttpMethod method, string url, string token)
    {
        var request = new HttpRequestMessage(method, url);
        request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", token);
        return request;
    }

    private async Task<HttpStatusCode> WhoAmIStatusAsync(string host, string token)
    {
        using var request = Request(HttpMethod.Get, $"https://{host}/api/data/v9.2/WhoAmI", token);
        return (await Client(host).SendAsync(request)).StatusCode;
    }

    /// <summary>Waits until <c>https://&lt;host&gt;/healthz</c> answers 200 through Caddy (502 while the host starts).</summary>
    private async Task WaitHealthyAsync(HostProcess process, string host)
    {
        var deadline = DateTime.UtcNow + TimeSpan.FromMinutes(4);
        var last = "";
        while (DateTime.UtcNow < deadline)
        {
            if (process.HasExited) throw new Xunit.Sdk.XunitException($"{process.Name} exited with {process.ExitCode}:\n{process.Output}");
            try
            {
                var status = (await Client(host).GetAsync($"https://{host}/healthz")).StatusCode;
                if (status == HttpStatusCode.OK) return;
                last = ((int)status).ToString(System.Globalization.CultureInfo.InvariantCulture);
            }
            catch (HttpRequestException ex)
            {
                last = ex.ToString();
            }
            await Task.Delay(500);
        }
        throw new Xunit.Sdk.XunitException($"https://{host}/healthz did not answer 200 (last: {last}):\n{process.Output}");
    }

    /// <summary>Waits until the host answers /healthz directly, so the reload's new site has a live upstream.</summary>
    private async Task WaitListeningAsync(HostProcess process)
    {
        using var http = new HttpClient(new SocketsHttpHandler { UseProxy = false }) { Timeout = TimeSpan.FromSeconds(10) };
        var deadline = DateTime.UtcNow + TimeSpan.FromMinutes(4);
        while (DateTime.UtcNow < deadline)
        {
            if (process.HasExited) throw new Xunit.Sdk.XunitException($"{process.Name} exited with {process.ExitCode}:\n{process.Output}");
            try
            {
                if ((await http.GetAsync($"http://{_gateway}:{process.Port}/healthz")).StatusCode == HttpStatusCode.OK) return;
            }
            catch (HttpRequestException) { }
            await Task.Delay(500);
        }
        throw new Xunit.Sdk.XunitException($"{process.Name} did not answer /healthz:\n{process.Output}");
    }

    private static string Audience(string jwt)
    {
        var payload = jwt.Split('.')[1].Replace('-', '+').Replace('_', '/');
        payload = payload.PadRight(payload.Length + (4 - payload.Length % 4) % 4, '=');
        using var doc = JsonDocument.Parse(Convert.FromBase64String(payload));
        return doc.RootElement.GetProperty("aud").GetString()!;
    }

    private static void CopyDirectory(string from, string to)
    {
        Directory.CreateDirectory(to);
        foreach (var file in Directory.GetFiles(from)) File.Copy(file, Path.Combine(to, Path.GetFileName(file)), true);
    }
}

