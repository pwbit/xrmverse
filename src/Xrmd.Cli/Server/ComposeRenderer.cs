using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

namespace Xrmd.Cli.Server;

/// <summary>
/// Renders <c>docker-compose.yml</c> from an <see cref="Installation"/>: the head and the <c>sqlserver</c>/<c>backups-init</c>
/// services of <c>Templates/docker-compose.yml</c> (omitted with an external SQL Server, ruling M8), then one
/// <c>Templates/compose-org.yml</c> block per organization.
/// </summary>
/// <remarks>
/// Template sections between <c>#{{NAME_BEGIN}}</c>/<c>#{{NAME_END}}</c> are kept only when the section is selected, and
/// the marker lines are always removed: <c>SQL</c> with the bundled SQL Server, <c>POSTGRES</c> with the bundled PostgreSQL
/// (plan 2.7a, <c>STORAGE_PROVIDER=PostgreSql</c>; per organization also <c>PG</c>, its <c>Storage__Provider</c>), <c>EXTERNAL</c>
/// with an external server of either engine (and <c>EXTSQL</c>, the <c>.bak</c> directory, with an external SQL Server); the head
/// always has the <c>backups</c> volume (plan 2.7b, ruling Q8: PostgreSQL's <c>pg_dump</c> writes there too); per
/// organization <c>PORTS</c> unless the Caddy proxy alone reaches it (H6), <c>LOCAL</c> without a public host and
/// <c>PUBLIC</c> and <c>PROXY</c> with one (I8, H3), plus <c>EDGE</c> behind the Caddy proxy. With the Caddy proxy
/// (<see cref="ProxyMode.Caddy"/>) the head keeps <c>CADDY</c> (the <c>edge</c> network and the <c>caddy-data</c> volume)
/// and <c>Templates/compose-proxy.yml</c> follows the organizations, with <c>FILES</c> for <c>TLS_MODE=files</c> (H3, H5).
/// An organization with a SQL endpoint (plan 3.3, <c>ORG_&lt;ORG&gt;_TDS_PORT</c>) keeps <c>TDS</c> (and <c>PORTKEY</c>, the
/// <c>ports:</c> line it shares with <c>PORTS</c>); the head then keeps <c>TDS</c>, the <c>tds-certs</c> service, with
/// <c>TDSCADDY</c> (Caddy's storage) or <c>TDSFILES</c> (a pair in <c>certs/</c>) as its source (ruling T12). With the local
/// identity provider (<c>AUTH_MODE=Local</c>) an organization keeps <c>IDP</c> and its wait for <c>secrets-init</c>:
/// <c>IDPSQL</c> beside the bundled SQL Server, <c>IDPPG</c> beside the bundled PostgreSQL (plan 2.7b), <c>IDPEXT</c> with an
/// external server.
/// </remarks>
public static partial class ComposeRenderer
{
    /// <summary>The start of the first line of every rendered file; a compose file without it is never overwritten (M1).</summary>
    public const string Header = "# Generated by xrmd";

    /// <summary>
    /// The image of the <c>proxy</c> service (H10): a pinned Caddy 2.x patch tag, never redistributed (I6). Upgrading it is a
    /// CLI release; <c>docs/install.md</c> names the same tag.
    /// </summary>
    public const string CaddyImage = "caddy:2.11.9";

    /// <summary>
    /// The image of the bundled <c>postgres</c> service of PostgreSQL organizations (plan 2.7a, <c>server init --database
    /// postgresql</c>): the official PostgreSQL 16 image, pulled by the user's compose, never redistributed (PostgreSQL License).
    /// </summary>
    public const string PostgresImage = "postgres:16-alpine";

    private const string OrgsMarker = "#{{ORGS}}";

    private const string TdsScriptMarker = "{{TDS_SCRIPT}}";

    /// <summary>How often <c>tds-certs</c> copies the pairs from Caddy's ACME storage (ruling T12): every 12 hours.</summary>
    public const int TdsInterval = 12 * 60 * 60;

    /// <summary>
    /// With the pair in <c>certs/</c> (<c>TLS_MODE=files</c> or your own proxy) every 5 minutes: the operator replaces those files
    /// by hand and expects the endpoint to follow soon; a check of two local files and a <c>cmp</c> costs nothing.
    /// </summary>
    public const int TdsLocalPairInterval = 5 * 60;

    /// <summary>
    /// With Caddy's internal CA every hour instead: it issues leaves valid for 12 hours and renews them after about 8, so a
    /// 12-hour copy could leave the SQL endpoint serving an expired certificate.
    /// </summary>
    public const int TdsInternalInterval = 60 * 60;

    public static bool IsGenerated(string compose) =>
        compose.StartsWith(Header + " ", StringComparison.Ordinal) || compose.StartsWith(Header + "\n", StringComparison.Ordinal);

    public static string Render(Installation installation)
    {
        if (installation.Orgs.Count == 0)
            throw new CliException(ExitCodes.Rejected,
                $"The installation in {installation.Directory} would have no organization: an installation needs at least one organization " +
                "(to remove everything, use `xrmd server down --volumes`).");
        // The database server: the bundled sqlserver or postgres service (plan 2.7a), or an external one (SQL_CONNECTION).
        var sql = installation.ExternalSql ? "EXTERNAL" : installation.IsPostgres ? "POSTGRES" : "SQL";
        var proxy = installation.Proxy;
        var proxyAddress = proxy == ProxyMode.Caddy ? installation.ProxyAddress : ""; // exit 5 on an unusable EDGE_SUBNET
        var localIdp = installation.IsLocalAuth;
        var orgTemplate = ReadTemplate("compose-org.yml");
        var orgs = new StringBuilder();
        foreach (var org in installation.Orgs)
        {
            Installation.ValidateOrgName(org.Name); // the name is pasted into YAML verbatim
            var sections = new HashSet<string> { sql };
            if (installation.IsPostgres) sections.Add("PG"); // Storage:Provider
            // The .bak directory on the external SQL Server's host; PostgreSQL's backups are pg_dump's, in /var/lib/xrmd/backups (Q8).
            if (installation.ExternalSql && !installation.IsPostgres) sections.Add("EXTSQL");
            if (localIdp) sections.UnionWith(["IDP", installation.ExternalSql ? "IDPEXT" : installation.IsPostgres ? "IDPPG" : "IDPSQL"]);
            var trusted = "";
            if (org.TdsPort is not null) sections.UnionWith(["TDS", "PORTKEY"]);
            if (org.Host is null)
            {
                sections.Add("LOCAL");
                sections.UnionWith(["PORTS", "PORTKEY"]);
            }
            else
            {
                if (Installation.ValidateHost(org.Host) is { } problem) throw new InvalidOperationException(problem); // pasted verbatim too
                sections.Add("PUBLIC");
                sections.Add("PROXY");
                // H6: behind Caddy the organization publishes no host port unless EXPOSE_PORTS; the customer's proxy needs it.
                if (proxy == ProxyMode.External || installation.ExposePorts) sections.UnionWith(["PORTS", "PORTKEY"]);
                // H3: Caddy has a fixed address on the edge network; the customer's proxy is TRUSTED_PROXIES.
                trusted = proxy == ProxyMode.External
                    ? "${" + Installation.TrustedProxiesKey + ":?set " + Installation.TrustedProxiesKey + " in .env}"
                    : proxyAddress;
                if (proxy == ProxyMode.Caddy) sections.Add("EDGE");
            }
            orgs.Append('\n').Append(Sections(orgTemplate, sections)
                .Replace("{{ORG_KEY}}", org.Name.ToUpperInvariant(), StringComparison.Ordinal)
                .Replace("{{ORG}}", org.Name, StringComparison.Ordinal)
                .Replace("{{HOST}}", org.Host ?? "", StringComparison.Ordinal)
                .Replace("{{TRUSTED_PROXIES}}", trusted, StringComparison.Ordinal));
        }

        var headSections = new HashSet<string> { sql };
        if (localIdp) headSections.Add("IDP");
        if (proxy == ProxyMode.Caddy)
        {
            headSections.Add("CADDY");
            // H3: the proxy waits for the organizations it serves; those without a host are not behind it.
            var dependsOn = string.Join('\n', installation.Orgs.Where(o => o.Host is not null).Select(o => "      - xrmd-" + o.Name));
            orgs.Append('\n').Append(Sections(ReadTemplate("compose-proxy.yml"), installation.TlsMode == "files" ? new HashSet<string> { "FILES" } : [])
                .Replace("{{CADDY_IMAGE}}", CaddyImage, StringComparison.Ordinal)
                .Replace("{{PROXY_ADDRESS}}", proxyAddress, StringComparison.Ordinal)
                .Replace("{{DEPENDS_ON}}", dependsOn, StringComparison.Ordinal));
        }
        var pair = installation.TdsPairSource;
        if (installation.HasTds) headSections.UnionWith(["TDS", pair.Length == 0 ? "TDSCADDY" : "TDSFILES"]);
        var tdsOrgs = string.Join(' ', installation.Orgs.Where(o => o.TdsPort is not null).Select(o => o.Name + "=" + o.Host));
        var head = Sections(ReadTemplate("docker-compose.yml"), headSections)
            .Replace("{{EDGE_SUBNET}}", proxy == ProxyMode.Caddy ? installation.EdgeSubnet : "", StringComparison.Ordinal)
            .Replace("{{EDGE_IP_RANGE}}", proxy == ProxyMode.Caddy ? installation.EdgeIpRange : "", StringComparison.Ordinal)
            .Replace("{{POSTGRES_IMAGE}}", PostgresImage, StringComparison.Ordinal)
            .Replace("{{TDS_ORGS}}", tdsOrgs, StringComparison.Ordinal)
            .Replace("{{TDS_PAIR}}", pair, StringComparison.Ordinal)
            .Replace("{{TDS_INTERVAL}}", TdsCopyInterval(installation).ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal)
            .Replace(TdsScriptMarker, TdsCertsScript(), StringComparison.Ordinal);
        if (!head.Contains(OrgsMarker + "\n", StringComparison.Ordinal))
            throw new InvalidOperationException($"The compose template has no {OrgsMarker} line.");
        var text = head.Replace(OrgsMarker + "\n", orgs.ToString(), StringComparison.Ordinal);
        if (text.Contains("{{", StringComparison.Ordinal))
            throw new InvalidOperationException("The rendered compose file still holds a template placeholder.");
        return text;
    }

    /// <summary>The seconds between two copies of <c>tds-certs</c>: 5 minutes for a pair in <c>certs/</c>, 1 hour with Caddy's internal CA, else 12 hours.</summary>
    public static int TdsCopyInterval(Installation installation) =>
        installation.TdsPairSource.Length > 0 ? TdsLocalPairInterval : installation.UsesInternalCa ? TdsInternalInterval : TdsInterval;

    /// <summary>
    /// The script of <c>tds-certs</c> (<c>Templates/tds-certs.sh</c>) as the body of a YAML literal block, eight spaces in, with
    /// <c>$</c> doubled so that Compose interpolates nothing in it.
    /// </summary>
    private static string TdsCertsScript() =>
        string.Join('\n', ReadTemplate("tds-certs.sh").Replace("\r\n", "\n").TrimEnd('\n').Split('\n')
            .Select(line => line.Length == 0 ? "" : "        " + line.Replace("$", "$$", StringComparison.Ordinal)));

    /// <summary>Keeps the <paramref name="selected"/> sections, drops the others and removes every marker line.</summary>
    internal static string Sections(string template, IReadOnlySet<string> selected)
    {
        var builder = new StringBuilder();
        string? skipping = null;
        foreach (var line in template.Replace("\r\n", "\n").Split('\n'))
        {
            if (SectionMarker().Match(line) is { Success: true } marker)
            {
                var section = marker.Groups[1].Value;
                if (marker.Groups[2].Value == "BEGIN")
                {
                    if (skipping is null && !selected.Contains(section)) skipping = section;
                }
                else if (skipping == section)
                {
                    skipping = null;
                }
                continue;
            }
            if (skipping is null) builder.Append(line).Append('\n');
        }
        var text = builder.ToString();
        return text.EndsWith("\n\n", StringComparison.Ordinal) ? text[..^1] : text; // Split adds one empty line after the final \n
    }

    internal static string ReadTemplate(string name)
    {
        var assembly = Assembly.GetExecutingAssembly();
        using var stream = assembly.GetManifestResourceStream("Xrmd.Cli.Templates." + name)
            ?? throw new InvalidOperationException($"Embedded template '{name}' is missing.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    [GeneratedRegex(@"^#\{\{([A-Z]+)_(BEGIN|END)\}\}\z")]
    private static partial Regex SectionMarker();
}
