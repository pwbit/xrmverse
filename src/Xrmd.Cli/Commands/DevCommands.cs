using System.CommandLine;
using System.Globalization;
using System.Text.Json;
using System.Text.Json.Nodes;
using Microsoft.Xrm.Sdk.Metadata;
using Xrmd.Cli.Http;
using Xrmd.Metadata;

namespace Xrmd.Cli.Commands;

/// <summary>
/// <c>xrmd dev</c>: development helpers. <c>dev seed</c> creates plausible rows from a table's metadata through the Web API:
/// strings <c>"{label} {n}"</c> (cut to MaxLength), numbers inside Min/MaxValue and Precision, a random option of a choice,
/// a random existing row of the target for a lookup (null for an optional lookup one time in five), dates within 2024–2026.
/// Columns that are read-only on create, the primary id and the owner (the caller) are not set. <c>--seed</c> makes the
/// data repeatable (same metadata, same existing target rows, same data).
/// </summary>
public static class DevCommands
{
    public static Command Build(CliContext ctx) => new("dev", "Development helpers.") { Seed(ctx) };

    private static Command Seed(CliContext ctx)
    {
        var table = new Argument<string>("table") { Description = "Logical name of the table." };
        var count = new Option<int>("--count") { Description = "Number of rows to create.", DefaultValueFactory = _ => 10 };
        var seed = new Option<int?>("--seed") { Description = "Seed of the random generator: the same seed gives the same data." };
        var command = new Command("seed", "Create plausible sample rows in a table.") { table, count, seed };
        command.SetAction(async (parse, ct) =>
        {
            var rowCount = parse.GetValue(count);
            if (rowCount is < 1 or > 100_000) throw new CliException(ExitCodes.Usage, "--count must be between 1 and 100000.");

            var client = ctx.CreateClient();
            var info = await DataTable.LoadAsync(client, parse.GetValue(table)!, ct);
            foreach (var (skipped, type) in info.Unsupported)
                await ctx.Env.Err.WriteLineAsync(info.SkipMessage(skipped, type, "dev seed", "not seeded"));
            var seeder = await Seeder.CreateAsync(client, info, new Random(parse.GetValue(seed) ?? Random.Shared.Next()), ctx.Env.Err, ct);
            var rows = Enumerable.Range(1, rowCount).Select(n => (n, seeder.NewRow(n))).ToList();

            var run = await RowWriter.CreateAsync(client, info.EntitySet, rows, 8, ct);
            var failures = run.Failures;
            if (run.Aborted is not null) return await RowWriter.ReportAsync(ctx.Env.Err, rowCount, failures, run);
            ctx.WriteResult(new { table = info.Name, created = rowCount - failures.Count, failed = failures.Count, failures },
                $"Created {rowCount - failures.Count} of {rowCount} rows in '{info.Name}'.");
            return await RowWriter.ReportAsync(ctx.Env.Err, rowCount, failures, run);
        });
        return command;
    }

    private sealed class Seeder
    {
        private static readonly DateTime DateAnchor = new(2024, 1, 1, 0, 0, 0, DateTimeKind.Utc);
        private const int DateSpanDays = 3 * 365;
        private const int ExistingRows = 100;

        private readonly DataTable _table;
        private readonly Random _random;
        private readonly List<AttributeMetadata> _columns;
        private readonly Dictionary<string, List<(string Table, Guid Id)>> _targets; // lookup column → existing rows
        private readonly Dictionary<string, string> _sets;
        private readonly Dictionary<string, IReadOnlyList<int>> _options;

        private Seeder(DataTable table, Random random, List<AttributeMetadata> columns, Dictionary<string, List<(string, Guid)>> targets,
            Dictionary<string, string> sets, Dictionary<string, IReadOnlyList<int>> options)
        {
            (_table, _random, _columns, _targets, _sets, _options) = (table, random, columns, targets, sets, options);
        }

        public static async Task<Seeder> CreateAsync(XrmdClient client, DataTable table, Random random, TextWriter err, CancellationToken ct)
        {
            var columns = new List<AttributeMetadata>();
            var targets = new Dictionary<string, List<(string, Guid)>>(StringComparer.Ordinal);
            var sets = new Dictionary<string, string>(StringComparer.Ordinal);
            var options = new Dictionary<string, IReadOnlyList<int>>(StringComparer.Ordinal);

            foreach (var column in table.Columns)
            {
                // The primary id is generated by the server; the owner defaults to the caller; read-only and stored-elsewhere columns cannot be set.
                if (column.LogicalName == table.PrimaryId || !table.IsWritable(column) || column.AttributeType == AttributeTypeCode.Owner
                    || column is StateAttributeMetadata or StatusAttributeMetadata)
                    continue;

                switch (column)
                {
                    case LookupAttributeMetadata lookup:
                        var existing = new List<(string, Guid)>();
                        foreach (var target in lookup.Targets ?? [])
                        {
                            if (!sets.TryGetValue(target, out var set)) sets[target] = set = await DataTable.EntitySetAsync(client, target, ct);
                            var targetId = await UserRoleLookup.PrimaryIdAsync(client, target, ct);
                            // Active rows only (every table has statecode, 0 is active): an inactive record, such as a deactivated
                            // currency, is refused as a lookup value by the server, and so is a currency without a rate a record can
                            // store (none, or out of range).
                            var filter = target == CurrencySchema.Table
                                ? string.Create(CultureInfo.InvariantCulture,
                                    $"statecode eq 0 and {CurrencySchema.ExchangeRate} ge {CurrencySchema.MinRate} and {CurrencySchema.ExchangeRate} le {CurrencySchema.MaxRate}")
                                : "statecode eq 0";
                            foreach (var row in await Page(client, $"{set}?$select={targetId}&$filter={filter}&$orderby={targetId}&$top={ExistingRows}", ct))
                                if (row.TryGetProperty(targetId, out var id) && Guid.TryParse(id.GetString(), out var guid)) existing.Add((target, guid));
                        }
                        targets[column.LogicalName] = existing;
                        break;
                    case PicklistAttributeMetadata or MultiSelectPicklistAttributeMetadata:
                        var values = await OptionValuesAsync(client, (EnumAttributeMetadata)column, ct);
                        if (values.Count == 0)
                        {
                            await err.WriteLineAsync($"Skipped column '{column.LogicalName}': it has no options to choose from.");
                            continue;
                        }
                        options[column.LogicalName] = values;
                        break;
                }
                columns.Add(column);
            }
            return new Seeder(table, random, columns, targets, sets, options);
        }

        private static async Task<IReadOnlyList<JsonElement>> Page(XrmdClient client, string query, CancellationToken ct)
        {
            var response = await client.SendJsonAsync(HttpMethod.Get, query, cancellationToken: ct);
            return response.Json is { } page && page.TryGetProperty("value", out var value) ? value.EnumerateArray().ToList() : [];
        }

        /// <summary>The option values of a choice column: its own, or those of the global choice it uses.</summary>
        private static async Task<IReadOnlyList<int>> OptionValuesAsync(XrmdClient client, EnumAttributeMetadata column, CancellationToken ct)
        {
            var own = column.OptionSet?.Options?.Where(o => o.Value is not null).Select(o => o.Value!.Value).ToList() ?? [];
            if (own.Count > 0 || column.OptionSet?.Name is not { Length: > 0 } name) return own;
            var global = await client.GetJsonAsync($"GlobalOptionSetDefinitions(Name={UserRoleLookup.Literal(name)})", ct);
            return global.TryGetProperty("Options", out var list) && list.ValueKind == JsonValueKind.Array
                ? list.EnumerateArray().Where(o => o.TryGetProperty("Value", out var v) && v.ValueKind == JsonValueKind.Number).Select(o => o.GetProperty("Value").GetInt32()).ToList()
                : [];
        }

        public JsonObject NewRow(int n)
        {
            var body = new JsonObject();
            foreach (var column in _columns)
            {
                switch (column)
                {
                    case LookupAttributeMetadata lookup:
                        var choices = _targets[column.LogicalName];
                        var required = lookup.RequiredLevel?.Value is AttributeRequiredLevel.ApplicationRequired or AttributeRequiredLevel.SystemRequired;
                        var skip = !required && (choices.Count == 0 || _random.Next(5) == 0);
                        if (choices.Count > 0 && !skip)
                        {
                            var (target, id) = choices[_random.Next(choices.Count)];
                            body[_table.Navigation(lookup, target) + "@odata.bind"] = $"/{_sets[target]}({id})";
                        }
                        else _ = _random.Next(); // keep the generator in step whether or not a target exists
                        break;
                    default:
                        body[column.LogicalName] = Value(column, n);
                        break;
                }
            }
            return body;
        }

        private JsonNode? Value(AttributeMetadata column, int n)
        {
            var invariant = CultureInfo.InvariantCulture;
            switch (column)
            {
                case StringAttributeMetadata s:
                    return JsonValue.Create(Text(Label(column), n, s.MaxLength ?? 100));
                case MemoAttributeMetadata m:
                    return JsonValue.Create(Text(Label(column), n, m.MaxLength ?? 2000));
                case IntegerAttributeMetadata i:
                    var (lo, hi) = Window(i.MinValue, i.MaxValue);
                    return JsonValue.Create((int)Math.Clamp(_random.NextInt64((long)lo, (long)hi + 1), i.MinValue ?? int.MinValue, i.MaxValue ?? int.MaxValue));
                case BigIntAttributeMetadata b:
                    var (blo, bhi) = Window(b.MinValue, b.MaxValue);
                    return JsonValue.Create(Math.Clamp(_random.NextInt64((long)blo, (long)bhi + 1), b.MinValue ?? long.MinValue, b.MaxValue ?? long.MaxValue));
                case DecimalAttributeMetadata d:
                    return JsonValue.Create(Round(Next((double?)d.MinValue, (double?)d.MaxValue), d.Precision ?? 2, d.MinValue, d.MaxValue));
                case MoneyAttributeMetadata money:
                    return JsonValue.Create(Round(Next(money.MinValue, money.MaxValue), money.Precision ?? 2,
                        money.MinValue is { } mlo ? (decimal)Math.Max(mlo, -7e28) : null, money.MaxValue is { } mhi ? (decimal)Math.Min(mhi, 7e28) : null));
                case DoubleAttributeMetadata f:
                    var rounded = Math.Round(Next(f.MinValue, f.MaxValue), Math.Clamp(f.Precision ?? 2, 0, 15));
                    return JsonValue.Create(Math.Clamp(rounded, f.MinValue ?? double.MinValue, f.MaxValue ?? double.MaxValue));
                case BooleanAttributeMetadata:
                    return JsonValue.Create(_random.Next(2) == 1);
                case DateTimeAttributeMetadata:
                    var when = DateAnchor.AddDays(_random.Next(DateSpanDays)).AddSeconds(_random.Next(86_400));
                    return JsonValue.Create(when.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", invariant));
                case PicklistAttributeMetadata:
                    return JsonValue.Create(_options[column.LogicalName][_random.Next(_options[column.LogicalName].Count)]);
                case MultiSelectPicklistAttributeMetadata:
                    var all = _options[column.LogicalName];
                    var chosen = all.Where(_ => _random.Next(2) == 1).OrderBy(v => v).ToList();
                    if (chosen.Count == 0) chosen.Add(all[_random.Next(all.Count)]);
                    return JsonValue.Create(string.Join(',', chosen));
                case UniqueIdentifierAttributeMetadata:
                    var bytes = new byte[16];
                    _random.NextBytes(bytes);
                    return JsonValue.Create(new Guid(bytes).ToString("D"));
                default:
                    // Unreachable: only plain data columns (DataTable.IsWritable) reach here; the others are DataTable.Unsupported,
                    // which the command names as skipped.
                    throw new InvalidOperationException($"dev seed has no generator for the column '{column.LogicalName}' ({column.AttributeType}).");
            }
        }

        private static string Label(AttributeMetadata column) =>
            column.DisplayName?.UserLocalizedLabel?.Label is { Length: > 0 } label ? label : column.LogicalName;

        /// <summary><c>"{label} {n}"</c> cut to <paramref name="max"/> characters, keeping as much of the number as possible.</summary>
        private static string Text(string label, int n, int max)
        {
            var number = n.ToString(CultureInfo.InvariantCulture);
            var text = $"{label} {number}";
            if (text.Length <= max) return text;
            return max >= number.Length + 2 ? label[..(max - number.Length - 1)] + " " + number : number[..Math.Min(number.Length, max)];
        }

        /// <summary>The range numbers are drawn from: the metadata range, narrowed to a plausible 0–1000 when it is wider.</summary>
        private static (double Low, double High) Window(double? min, double? max)
        {
            var low = min ?? double.MinValue;
            var high = max ?? double.MaxValue;
            var (plausibleLow, plausibleHigh) = (Math.Max(low, 0), Math.Min(high, 1000));
            return plausibleLow <= plausibleHigh ? (plausibleLow, plausibleHigh) : (low, Math.Min(high, low + 1000));
        }

        private static (long Low, long High) Window(long? min, long? max)
        {
            var (low, high) = Window((double?)min, (double?)max);
            return ((long)Math.Max(low, min ?? long.MinValue), (long)Math.Min(high, max ?? long.MaxValue));
        }

        private static (int Low, int High) Window(int? min, int? max)
        {
            var (low, high) = Window((long?)min, (long?)max);
            return ((int)low, (int)high);
        }

        private double Next(double? min, double? max)
        {
            var (low, high) = Window(min, max);
            return low + _random.NextDouble() * (high - low);
        }

        private static decimal Round(double value, int precision, decimal? min, decimal? max)
        {
            var rounded = Math.Round((decimal)value, Math.Clamp(precision, 0, 10));
            if (min is { } lo && rounded < lo) rounded = Math.Ceiling(lo * Pow10(precision)) / Pow10(precision);
            if (max is { } hi && rounded > hi) rounded = Math.Floor(hi * Pow10(precision)) / Pow10(precision);
            return rounded;
        }

        private static decimal Pow10(int precision) => (decimal)Math.Pow(10, Math.Clamp(precision, 0, 10));
    }
}
